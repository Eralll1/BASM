#!/usr/bin/env python3
"""Video -> per-frame delta lists of (x, y) pixels to toggle.

Frame 0 starts from all-black (all-zero). Each subsequent frame is the set of
pixels whose value differs from the previous frame. Toggle semantics:
applying a frame flips fb[y*W + x] for every (x, y) in that frame.

This module does NOT write a file. It returns (or yields) Python data.
Use write_c_header() if you later want to embed the data into your C program.
"""

import subprocess
from pathlib import Path

import numpy as np
from PIL import Image


# ---------- video plumbing --------------------------------------------------

def probe_video(path):
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-select_streams", "v:0",
         "-show_entries", "stream=width,height,r_frame_rate",
         "-of", "default=noprint_wrappers=1", str(path)],
        capture_output=True, text=True, check=True,
    ).stdout
    d = dict(line.split("=", 1) for line in out.strip().splitlines())
    num, den = d["r_frame_rate"].split("/")
    return int(d["width"]), int(d["height"]), float(num) / float(den)


def _iter_rgb(path, out_w, out_h, fps):
    src_w, src_h, _ = probe_video(path)
    cmd = ["ffmpeg", "-loglevel", "error", "-i", str(path)]
    if fps is not None:
        cmd += ["-vf", f"fps={fps}"]
    cmd += ["-f", "rawvideo", "-pix_fmt", "rgb24", "-"]
    proc = subprocess.Popen(cmd, stdout=subprocess.PIPE)

    src_size = src_w * src_h * 3
    while True:
        raw = proc.stdout.read(src_size)
        if len(raw) < src_size:
            break
        rgb = np.frombuffer(raw, dtype=np.uint8).reshape(src_h, src_w, 3)
        img = Image.fromarray(rgb).resize((out_w, out_h),
                                          Image.Resampling.LANCZOS)
        yield np.asarray(img)
    proc.wait()


def _to_bits(rgb, threshold):
    gray = 0.299 * rgb[..., 0] + 0.587 * rgb[..., 1] + 0.114 * rgb[..., 2]
    return (gray > threshold).astype(np.uint8)


# ---------- the API you asked for ------------------------------------------

def iter_delta_frames(video_path, width=125, height=125, fps=15,
                      threshold=128):
    """Yield one list[(x, y)] per frame — memory-friendly streaming form.

    >>> for i, frame in enumerate(iter_delta_frames("badapple.mp4")):
    ...     print(i, len(frame), "toggles")
    """
    prev = np.zeros((height, width), dtype=np.uint8)
    for rgb in _iter_rgb(video_path, width, height, fps):
        cur = _to_bits(rgb, threshold)
        ys, xs = np.nonzero(cur != prev)          # already (row, col)
        yield list(zip(xs.tolist(), ys.tolist()))  # -> (x, y)
        prev = cur


def generate_frames(video_path, width=125, height=125, fps=15,
                    threshold=128):
    """Return list[list[(x, y)]] — the whole animation in memory.

    WARNING: full Bad Apple at 15 fps is ~500 MB of Python tuples.
    Use iter_delta_frames() unless you have a reason to hold everything.
    """
    return list(iter_delta_frames(video_path, width, height, fps, threshold))


# ---------- optional: turn the lists into a C header -----------------------

def write_c_header(frames, path, width=125, height=125, fps=15):
    """Emit a self-contained .h with packed uint16 (x<<8 | y) toggles.

    Requires width, height <= 256 so a pixel index fits in one byte.
    Access from C:
        for (uint32_t i = 0; i < BA_FRAME[n].count; i++) {
            uint16_t v = BA_DATA[BA_FRAME[n].offset + i];
            fb[(v & 0xFF) * BA_W + (v >> 8)] ^= 1;   // y*W + x
        }
    """
    if width > 256 or height > 256:
        raise ValueError("write_c_header: width/height must be <= 256")

    offsets = []
    running = 0
    for frame in frames:
        offsets.append((running, len(frame)))
        running += len(frame)

    with open(path, "w") as f:
        f.write("/* auto-generated by badapple_delta.py -- do not edit */\n")
        f.write("#include <stdint.h>\n")
        f.write(f"#define BA_W      {width}\n")
        f.write(f"#define BA_H      {height}\n")
        f.write(f"#define BA_FPS    {fps}\n")
        f.write(f"#define BA_FRAMES {len(frames)}\n\n")

        f.write("static const uint16_t BA_DATA[] = {\n")
        for frame in frames:
            packed = [(x << 8) | y for (x, y) in frame]
            for i in range(0, len(packed), 16):
                line = ",".join(f"0x{v:04X}" for v in packed[i:i + 16])
                f.write(f"  {line},\n")
        f.write("};\n\n")

        f.write("static const struct { uint32_t offset; uint16_t count; } "
                "BA_FRAME[] = {\n")
        for off, n in offsets:
            f.write(f"  {{ {off}, {n} }},\n")
        f.write("};\n")


# ---------- CLI for quick experiments --------------------------------------

if __name__ == "__main__":
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("video")
    ap.add_argument("--size", default="125", help="125 or 125x125")
    ap.add_argument("--fps", type=float, default=15)
    ap.add_argument("--threshold", type=int, default=128)
    ap.add_argument("--max-frames", type=int, default=None,
                    help="stop after N frames (useful for quick checks)")
    args = ap.parse_args()

    if "x" in args.size:
        w, h = map(int, args.size.split("x"))
    else:
        w = h = int(args.size)

    # Streaming path — never holds the whole thing in RAM.
    frames = []
    for i, frame in enumerate(iter_delta_frames(
            args.video, w, h, args.fps, args.threshold)):
        if i % 100 == 0:
            print(f"frame {i:5d}  toggles={len(frame):5d}", flush=True)
        if args.max_frames is not None and i + 1 >= args.max_frames:
            break
        frames.append(frame)
    

    with open("bad_bad_apple.stl", "w") as f:
        f.write("INIT_SCREEN 30\n")
        for ind, frame in enumerate(frames):
            f.write(f"; Frame {ind}\n")
            for x,y in frame:
                f.write(f"    MOVE {x+y*125} 0 %ax\n")
                f.write(f"    XOR 1 &ax &ax\n")
            f.write(f"DRAW\n\n")